# ============================================================
# ESOL-V Target Distribution Analysis
# Distribution of Measured Aqueous Solubility (logS)
# ============================================================

import re

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from datasets import load_dataset


# ------------------------------------------------------------
# Configuration
# ------------------------------------------------------------

DATASET_NAME = "molvision/ESOL-V-SMILES-0"


# ------------------------------------------------------------
# Load Dataset
# ------------------------------------------------------------

dataset = load_dataset(DATASET_NAME, split="train")

print("=" * 72)
print("ESOL-V TARGET DISTRIBUTION ANALYSIS")
print("=" * 72)

print(f"Dataset      : {DATASET_NAME}")
print(f"Samples      : {len(dataset)}")


# ------------------------------------------------------------
# Parse Regression Target
# ------------------------------------------------------------

def extract_logs(answer: str) -> float:
    """
    Extract the numeric logS target from the MolVision answer format.

    Example
    -------
    '<float>-2.484</float>' -> -2.484
    """
    match = re.search(
        r"<float>\s*([-+]?\d*\.?\d+)\s*</float>",
        answer,
    )

    return float(match.group(1)) if match else np.nan


targets = np.array(
    [
        extract_logs(answer)
        for answer in dataset["Answer"]
    ],
    dtype=float,
)

valid_targets = targets[~np.isnan(targets)]


# ------------------------------------------------------------
# Summary Statistics
# ------------------------------------------------------------

print("\n" + "=" * 72)
print("TARGET STATISTICS")
print("=" * 72)

print(f"Count      : {len(valid_targets)}")
print(f"Mean       : {np.mean(valid_targets):.3f}")
print(f"Median     : {np.median(valid_targets):.3f}")
print(f"Std Dev    : {np.std(valid_targets):.3f}")
print(f"Minimum    : {np.min(valid_targets):.3f}")
print(f"Maximum    : {np.max(valid_targets):.3f}")
print(f"25th pct   : {np.percentile(valid_targets, 25):.3f}")
print(f"75th pct   : {np.percentile(valid_targets, 75):.3f}")


# ------------------------------------------------------------
# Histogram
# ------------------------------------------------------------

plt.figure(figsize=(11, 6))

plt.hist(
    valid_targets,
    bins=20,
    edgecolor="black",
    alpha=0.8,
)

plt.axvline(
    np.mean(valid_targets),
    linestyle="--",
    linewidth=2,
    label=f"Mean = {np.mean(valid_targets):.2f}",
)

plt.axvline(
    np.median(valid_targets),
    linestyle=":",
    linewidth=2,
    label=f"Median = {np.median(valid_targets):.2f}",
)

plt.xlabel("Measured log Solubility (logS)")
plt.ylabel("Number of Molecules")
plt.title("ESOL-V Distribution of Measured Aqueous Solubility")
plt.legend()
plt.grid(axis="y", alpha=0.25)
plt.tight_layout()
plt.show()


# ------------------------------------------------------------
# Solubility Range Distribution
# ------------------------------------------------------------

bins = [
    -np.inf,
    -6,
    -4,
    -2,
    0,
    np.inf,
]

labels = [
    "logS < -6",
    "-6 ≤ logS < -4",
    "-4 ≤ logS < -2",
    "-2 ≤ logS < 0",
    "logS ≥ 0",
]

categories = pd.cut(
    valid_targets,
    bins=bins,
    labels=labels,
    right=False,
)

counts = (
    pd.Series(categories)
    .value_counts()
    .sort_index()
)

distribution_table = pd.DataFrame(
    {
        "Solubility Range": counts.index.astype(str),
        "Molecule Count": counts.values,
        "Percentage": (
            counts.values
            / len(valid_targets)
            * 100
        ).round(2),
    }
)

print("\n" + "=" * 72)
print("SOLUBILITY RANGE DISTRIBUTION")
print("=" * 72)

print(
    distribution_table.to_string(
        index=False
    )
)


# ------------------------------------------------------------
# Boxplot
# ------------------------------------------------------------

plt.figure(figsize=(11, 3))

plt.boxplot(
    valid_targets,
    vert=False,
)

plt.xlabel("Measured log Solubility (logS)")
plt.title("ESOL-V Solubility Range and Potential Outliers")
plt.grid(axis="x", alpha=0.25)
plt.tight_layout()
plt.show()


# ------------------------------------------------------------
# Research Observation
# ------------------------------------------------------------
#
# The ESOL-V target distribution is concentrated primarily between
# logS = -4 and logS = 0, with a smaller number of highly insoluble
# molecules extending into the lower tail.
#
# This imbalance should be considered during model evaluation because
# aggregate regression metrics may obscure poor performance on sparsely
# represented extreme-solubility compounds.