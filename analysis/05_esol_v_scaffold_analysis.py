from collections import Counter

import matplotlib.pyplot as plt
import pandas as pd
from datasets import load_dataset
from rdkit import Chem
from rdkit.Chem.Scaffolds import MurckoScaffold


# ------------------------------------------------------------
# Configuration
# ------------------------------------------------------------

DATASET_NAME = "molvision/ESOL-V-SMILES-0"


# ------------------------------------------------------------
# Load Dataset
# ------------------------------------------------------------

dataset = load_dataset(DATASET_NAME, split="train")

print("=" * 72)
print("ESOL-V SCAFFOLD DIVERSITY ANALYSIS")
print("=" * 72)

print(f"Dataset      : {DATASET_NAME}")
print(f"Samples      : {len(dataset)}")
print(f"Columns      : {dataset.column_names}")


# ------------------------------------------------------------
# Build Molecule Table
# ------------------------------------------------------------

molecule_df = pd.DataFrame(
    {
        "smiles": dataset["TargetMolecule"],
    }
)

print("\n" + "=" * 72)
print("MOLECULE COUNTS")
print("=" * 72)

print(f"Raw records          : {len(molecule_df)}")
print(f"Exact unique SMILES  : {molecule_df['smiles'].nunique()}")


# ------------------------------------------------------------
# Canonicalize SMILES
# ------------------------------------------------------------

def canonicalize_smiles(smiles: str):
    """
    Convert a SMILES string into its canonical RDKit representation.
    """
    mol = Chem.MolFromSmiles(smiles)

    if mol is None:
        return None

    return Chem.MolToSmiles(
        mol,
        canonical=True,
    )


molecule_df["canonical_smiles"] = (
    molecule_df["smiles"]
    .apply(canonicalize_smiles)
)

invalid_count = (
    molecule_df["canonical_smiles"]
    .isna()
    .sum()
)

valid_df = (
    molecule_df[
        molecule_df["canonical_smiles"].notna()
    ]
    .copy()
)

unique_df = (
    valid_df
    .drop_duplicates(
        subset="canonical_smiles"
    )
    .copy()
)

print(f"Invalid SMILES       : {invalid_count}")
print(f"Unique canonical mols: {len(unique_df)}")


# ------------------------------------------------------------
# Extract Bemis-Murcko Scaffolds
# ------------------------------------------------------------

def get_scaffold(smiles: str):
    """
    Extract the Bemis-Murcko scaffold for a molecule.

    Acyclic molecules are labeled separately because they do not
    produce a ring-based Murcko scaffold.
    """
    mol = Chem.MolFromSmiles(smiles)

    if mol is None:
        return None

    scaffold = MurckoScaffold.GetScaffoldForMol(mol)

    if scaffold.GetNumAtoms() == 0:
        return "[ACYCLIC]"

    return Chem.MolToSmiles(
        scaffold,
        canonical=True,
    )


unique_df["scaffold"] = (
    unique_df["canonical_smiles"]
    .apply(get_scaffold)
)


# ------------------------------------------------------------
# Scaffold Counts
# ------------------------------------------------------------

scaffold_counts = Counter(
    unique_df["scaffold"]
)

num_molecules = len(unique_df)
num_scaffolds = len(scaffold_counts)

singleton_scaffolds = sum(
    count == 1
    for count in scaffold_counts.values()
)

repeated_scaffolds = sum(
    count > 1
    for count in scaffold_counts.values()
)

largest_family = max(
    scaffold_counts.values()
)

diversity_ratio = (
    num_scaffolds
    / num_molecules
)

singleton_fraction = (
    singleton_scaffolds
    / num_scaffolds
)

acyclic_count = scaffold_counts.get(
    "[ACYCLIC]",
    0,
)


# ------------------------------------------------------------
# Scaffold Summary
# ------------------------------------------------------------

print("\n" + "=" * 72)
print("SCAFFOLD SUMMARY")
print("=" * 72)

print(f"Unique molecules          : {num_molecules}")
print(f"Unique scaffolds          : {num_scaffolds}")
print(f"Scaffold diversity ratio  : {diversity_ratio:.3f}")
print(f"Singleton scaffolds       : {singleton_scaffolds}")
print(f"Repeated scaffolds        : {repeated_scaffolds}")
print(f"Singleton fraction        : {singleton_fraction:.2%}")
print(f"Largest scaffold family   : {largest_family}")
print(f"Acyclic molecules         : {acyclic_count}")


# ------------------------------------------------------------
# Build Scaffold Table
# ------------------------------------------------------------

scaffold_table = pd.DataFrame(
    scaffold_counts.items(),
    columns=[
        "Scaffold",
        "Molecule Count",
    ],
)

scaffold_table = (
    scaffold_table
    .sort_values(
        "Molecule Count",
        ascending=False,
    )
    .reset_index(drop=True)
)

scaffold_table["Percentage"] = (
    scaffold_table["Molecule Count"]
    / num_molecules
    * 100
)

print("\n" + "=" * 72)
print("TOP 15 SCAFFOLDS")
print("=" * 72)

print(
    scaffold_table
    .head(15)
    .to_string(index=False)
)


# ------------------------------------------------------------
# Visualize Most Common Scaffold Families
# ------------------------------------------------------------

top_scaffolds = scaffold_table.head(15).copy()

top_scaffolds["Label"] = (
    top_scaffolds["Scaffold"]
    .apply(
        lambda scaffold:
        scaffold
        if len(scaffold) <= 35
        else scaffold[:32] + "..."
    )
)

plt.figure(figsize=(11, 7))

plt.barh(
    top_scaffolds["Label"][::-1],
    top_scaffolds["Molecule Count"][::-1],
)

plt.xlabel("Number of Unique Molecules")
plt.ylabel("Bemis-Murcko Scaffold")
plt.title("ESOL-V Most Common Molecular Scaffolds")
plt.tight_layout()
plt.show()


# ------------------------------------------------------------
# Scaffold Family Size Distribution
# ------------------------------------------------------------

family_sizes = pd.Series(
    list(scaffold_counts.values())
)

family_distribution = (
    family_sizes
    .value_counts()
    .sort_index()
    .rename_axis(
        "Molecules per Scaffold"
    )
    .reset_index(
        name="Number of Scaffolds"
    )
)

print("\n" + "=" * 72)
print("SCAFFOLD FAMILY SIZE DISTRIBUTION")
print("=" * 72)

print(
    family_distribution.to_string(
        index=False
    )
)


plt.figure(figsize=(9, 5))

plt.bar(
    family_distribution[
        "Molecules per Scaffold"
    ],
    family_distribution[
        "Number of Scaffolds"
    ],
)

plt.xlabel("Molecules Sharing the Same Scaffold")
plt.ylabel("Number of Scaffolds")
plt.title("ESOL-V Scaffold Family Size Distribution")
plt.tight_layout()
plt.show()


